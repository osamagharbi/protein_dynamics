#!/bin/bash
# ===========================================================================
#  setup_env.sh -- ONE-TIME: build the data-prep conda env on a Jean-Zay LOGIN
#  node (login nodes have internet; compute nodes do not).
#
#  Creates $ENV_PREFIX with pymol-open-source + MDAnalysis + MDAnalysisData,
#  runs the end-to-end selftest, and writes env.sh (sourced by every job).
#
#     ./setup_env.sh                       # default $WORK/envs/dsr_data
#     CONDA_MODULE=miniforge/24.9.0 ./setup_env.sh
# ===========================================================================
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_PREFIX="${ENV_PREFIX:-$WORK/envs/dsr_data}"
export CONDA_PKGS_DIRS="${CONDA_PKGS_DIRS:-$WORK/.conda/pkgs}"   # keep $HOME quota free

module purge
LOADED=""
for m in ${CONDA_MODULE:-miniforge anaconda-py3}; do
  if module load "$m" 2>/dev/null && command -v conda >/dev/null; then LOADED="$m"; break; fi
done
[ -n "$LOADED" ] || { echo "No conda module found (tried: ${CONDA_MODULE:-miniforge anaconda-py3})."
                      echo "Run 'module avail 2>&1 | grep -iE \"conda|forge\"' and re-run with CONDA_MODULE=<name>."; exit 1; }
echo "[setup] using module $LOADED -> $(command -v conda)"

if [ ! -x "$ENV_PREFIX/bin/python" ]; then
  conda create -y -p "$ENV_PREFIX" -c conda-forge --override-channels \
      python=3.11 pymol-open-source "mdanalysis>=2.7" numpy scipy
fi
"$ENV_PREFIX/bin/python" -m pip install --no-cache-dir "MDAnalysisData>=0.9"

cat > "$HERE/env.sh" <<EOF
# generated by setup_env.sh on $(date +%F) -- sourced by the data-prep jobs
export PATH="$ENV_PREFIX/bin:\$PATH"
export PYTHONNOUSERSITE=1
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 PYTHONUNBUFFERED=1
EOF

module purge
source "$HERE/env.sh"
python "$HERE/prep.py" selftest
echo "[setup] OK -> env.sh written; next: DRY_RUN=1 ./run_data_prep.sh"
